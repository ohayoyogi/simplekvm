_Static_assert(sizeof(kbd_report_t) == 8 && sizeof(abs_report_t) == 6 &&
               sizeof(rel_report_t) == 5, "report sizes");

void hidq_init(hidq_t *q, uint8_t report_size) {
  memset(q, 0, sizeof(*q));
  q->size = report_size;
}

void hidq_push(hidq_t *q, const void *report) {
  uint8_t idx;
  if (q->count == HIDQ_LEN) {
    idx = (uint8_t)((q->head + q->count - 1) % HIDQ_LEN);  // overwrite newest
  } else {
    idx = (uint8_t)((q->head + q->count) % HIDQ_LEN);
    q->count++;
  }
  memcpy(q->data[idx], report, q->size);
}

static int8_t sat8(int v) { return (int8_t)(v > 127 ? 127 : v < -127 ? -127 : v); }

void hidq_push_rel(hidq_t *q, const rel_report_t *r) {
  if (q->count) {
    rel_report_t *last = (rel_report_t *)q->data[(q->head + q->count - 1) % HIDQ_LEN];
    int x = last->x + r->x, y = last->y + r->y, w = last->wheel + r->wheel;
    // merge into the newest pending report when buttons did not change and
    // the sum still fits, or when the queue is full (keep it bounded)
    bool fits = x >= -127 && x <= 127 && y >= -127 && y <= 127 && w >= -127 && w <= 127;
    if (last->buttons == r->buttons && (fits || q->count == HIDQ_LEN)) {
      last->x = sat8(x);
      last->y = sat8(y);
      last->wheel = sat8(w);
      return;
    }
  }
  hidq_push(q, r);
}

const uint8_t *hidq_peek(const hidq_t *q) { return q->count ? q->data[q->head] : 0; }

void hidq_pop(hidq_t *q) {
  if (!q->count) return;
  q->head = (uint8_t)((q->head + 1) % HIDQ_LEN);
  q->count--;
}
