_Static_assert(sizeof(hid_desc_keyboard) == HID_DESC_KEYBOARD_LEN, "keyboard desc length");
_Static_assert(sizeof(hid_desc_mouse_abs) == HID_DESC_MOUSE_ABS_LEN, "abs mouse desc length");
